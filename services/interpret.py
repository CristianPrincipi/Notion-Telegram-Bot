"""A plain sentence → one of David's commands, written out in its syntax.

"ho speso 12 euro da Carrefour" → `Add e Carrefour 12 f`. This module only
WRITES the command; it never runs one. The bot layer (bot/sentences.py) checks
that the text fullmatches exactly one command in the registry, shows it, asks for
a confirmation before anything that writes, and only then hands it to the same
router a typed message goes through. So the model can propose nothing that a
typed command could not do, and nothing it proposes writes unseen.

WHY CLAUDE, AND WHY HAIKU
-------------------------
Regexes cannot read "domani alle 10 e mezza" or "quanto mi resta questo mese?".
A model can, and turning a sentence into one line of a known syntax is
classification and extraction — the work the cheapest model is for. It runs on
config.ANTHROPIC_INTERPRET_MODEL at a low effort with a small output cap, so a
sentence costs a few hundredths of a cent (CLAUDE.md: free, or a few cents a
month), and every call counts toward the same daily budget as Learn and
Implement.

WHAT IT IS GIVEN
----------------
The catalogue of commands, generated by david.py from COMMANDS — the same list
the help is generated from, so the model is never told about a command that does
not exist, or left ignorant of one that does. Plus today's date, so "venerdì" and
"domani" can be written as dates.

WHAT IT ANSWERS
---------------
Exactly one of three things, in a structured-output object:
  - `command`: the full command text, when the sentence asks for one and gives
    every part it needs;
  - `question`: one short question, when it asks for a command but leaves out a
    part that has no default (an amount, a time). The bot asks it, and the reply
    is read together with the original sentence;
  - both empty: it is not a request for anything David does.
"""

import logging

from clients.anthropic_client import complete_json
from clients.calendar_client import now_local
from config import (
    ANTHROPIC_INTERPRET_EFFORT,
    ANTHROPIC_INTERPRET_MAX_TOKENS,
    ANTHROPIC_INTERPRET_MODEL,
)

logger = logging.getLogger(__name__)

INTERPRET_SCHEMA = {
    "type": "object",
    "properties": {
        "command":  {"type": "string"},
        "question": {"type": "string"},
    },
    "required": ["command", "question"],
    "additionalProperties": False,
}

_WEEKDAYS = ("Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday")

_SYSTEM = """You turn a message sent to David — a personal Telegram bot that writes \
to Notion and Google Calendar — into ONE of David's commands, written out exactly \
in David's syntax. You never run anything: what you write is shown to the user, \
and checked against the real command list, before it runs.

David's commands. Words in [brackets] are parts you fill in; everything else is \
written exactly as shown:
{catalogue}

Today is {today}, in Italy.

How to answer:
- `command`: the full command text, every [part] filled in from the message. \
Write the command word exactly as above (`Add e`, `Remind`, `Agenda`, ...).
- Never invent a part the message does not give. If a part has no default and \
the message leaves it out — an amount, a time, a name — leave `command` empty \
and write in `question` ONE short question asking for exactly that part, in the \
language of the message.
- If the message is not a request for any of these commands (a greeting, a \
remark, a question David cannot answer), leave both empty.
- Exactly one command, never two. Only one of `command` and `question` is filled.
- Dates: `td` for today, `tr` for tomorrow, otherwise DD.MM (with .YYYY only for \
another year). Times: HH.MM, 24-hour, or a bare hour.
- An expense category or a book genre is its shortcut. Leave the category out \
when the message does not make it clear; it defaults to Food.
- Amounts use a dot for decimals: 12.50.
- When you are shown an earlier message, the question David asked about it and a
reply, the reply answers that question: complete the earlier request with it. A
one-letter reply is a shortcut (a genre, a category), not a command. Only if the
reply is a complete request on its own does it replace the earlier message."""

_EARLIER = """Earlier message: {sentence}
David asked: {question}
Reply: {reply}"""


def _today() -> str:
    today = now_local()
    return f"{_WEEKDAYS[today.weekday()]} {today:%d.%m.%Y}"


def interpret(text: str, catalogue: str, earlier: tuple[str, str] | None = None):
    """The command a sentence asks for. Returns (answer, error).

    `answer` is {"command": str, "question": str}, both stripped; at most one is
    non-empty. `earlier` is (sentence, question) when `text` replies to a
    question this module asked, so the two are read together.

    Synchronous — it blocks for the length of the Claude call. Callers run it
    with asyncio.to_thread.
    """
    user = text if earlier is None else _EARLIER.format(
        sentence=earlier[0], question=earlier[1], reply=text)
    answer, err = complete_json(
        _SYSTEM.format(catalogue=catalogue, today=_today()), user, INTERPRET_SCHEMA,
        max_tokens=ANTHROPIC_INTERPRET_MAX_TOKENS,
        effort=ANTHROPIC_INTERPRET_EFFORT,
        model=ANTHROPIC_INTERPRET_MODEL,
    )
    if err:
        return None, err

    command = answer["command"].strip()
    question = "" if command else answer["question"].strip()
    logger.info("Interpreted %r as command=%r question=%r", text[:200], command, question)
    return {"command": command, "question": question}, None
